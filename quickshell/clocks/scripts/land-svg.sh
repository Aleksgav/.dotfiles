#!/usr/bin/env bash
# Writes ../land.svg, the land silhouettes behind the map view, from Natural
# Earth's 1:110m land polygons (public domain, naturalearthdata.com).
#
# Run by hand, once; the widget only reads the SVG it writes, which is
# committed. Rerun it only to change the map's source data.
#
# The projection is plain equirectangular, one unit per degree: x = lon + 180,
# y = 90 - lat, on a 360x180 canvas. shell.qml maps longitude and latitude to
# pixels the same way, which is what keeps its markers and night shading on
# top of the right coastlines.

set -euo pipefail

SRC='https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
OUT="$(dirname "$0")/../land.svg"

# Every ring becomes one closed "M x,y L x,y ... Z" subpath of a single path.
# Rounded to a tenth of a degree, far finer than the widget's pixels.
path=$(curl -fsSL "$SRC" | jq -r '
  def pt: "\((.[0] + 180) * 10 | round / 10),\((90 - .[1]) * 10 | round / 10)";
  [ .features[].geometry
    | if .type == "Polygon" then [.coordinates] else .coordinates end
    | .[][]
    | "M" + (map(pt) | join("L")) + "Z" ]
  | join("")')

cat > "$OUT" <<EOF
<!-- Natural Earth 1:110m land, equirectangular. Generated by scripts/land-svg.sh. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 360 180">
<path fill="#ffffff" fill-rule="evenodd" d="$path"/>
</svg>
EOF
